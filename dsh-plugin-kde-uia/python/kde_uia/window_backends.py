"""Window backends beyond AT-SPI: KWin scripting (primary) and X11 EWMH (fallback).

AT-SPI knows the windows that opt into accessibility; KWin knows *every*
window, its stacking order, geometry and activation, and can activate, move
and screenshot windows regardless of the toolkit.  kde-uia therefore treats
KWin as the authority for window management whenever it is reachable, and
AT-SPI as the authority for element trees.

Backends:

* ``kwin`` - a small KWin script driven through ``org.kde.KWin`` /
  ``/Scripting`` (Plasma 5 and 6, X11 and Wayland).  The script reads one
  command from the script's KConfig section and writes one JSON answer to a
  temp file, which makes it work across separate CLI invocations.
* ``x11``  - ``wmctrl`` / ``xdotool`` / ``xprop`` on an X11 session.
* ``atspi`` - window frames reported by accessibility (no management).

Every subprocess runs with an explicit argument vector and a short timeout;
user input is never interpolated into a shell string.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .errors import BackendUnavailableError, KdeUiaError, NotFoundError, UsageError

_SCRIPT_NAME = "kde-uia-window-probe"
ACTIONS = ("activate", "focus", "minimize", "unminimize", "maximize", "restore", "move", "resize", "close")

_SCRIPT_JS = r"""// kde-uia window probe (generated by kde-uia; safe to delete).
function __uiaRect(g) { return {x: Math.round(g.x), y: Math.round(g.y), width: Math.round(g.width), height: Math.round(g.height)}; }
function __uiaOne(w) {
    var out = {id: String(w.internalId), caption: String(w.caption || ""),
               resourceClass: String(w.resourceClass || ""), resourceName: String(w.resourceName || ""),
               pid: Number(w.pid), layer: Number(w.layer), minimized: Boolean(w.minimized),
               active: workspace.activeWindow === w, frame: __uiaRect(w.frameGeometry),
               client: __uiaRect(w.clientGeometry)};
    try { out.desktop = Number(w.desktop); } catch (e) { out.desktop = -1; }
    try { out.onAllDesktops = Boolean(w.onAllDesktops); } catch (e) { out.onAllDesktops = false; }
    try { out.fullScreen = Boolean(w.fullScreen); } catch (e) { out.fullScreen = false; }
    try { out.output = String(w.output ? w.output.name : ""); } catch (e) { out.output = ""; }
    return out;
}
function __uiaList() {
    var list = [];
    var clients = workspace.clientList ? workspace.clientList() : [];
    for (var i = 0; i < clients.length; i++) list.push(__uiaOne(clients[i]));
    return JSON.stringify(list);
}
function __uiaOutputs() {
    var out = [];
    var list = workspace.screens ? workspace.screens : [];
    for (var i = 0; i < list.length; i++) {
        var s = list[i];
        out.push({name: String(s.name), x: Math.round(s.geometry.x), y: Math.round(s.geometry.y),
                  width: Math.round(s.geometry.width), height: Math.round(s.geometry.height),
                  scale: Number(s.devicePixelRatio || 1)});
    }
    return JSON.stringify(out);
}
function __uiaFind(id) {
    var want = String(id);
    var clients = workspace.clientList ? workspace.clientList() : [];
    for (var i = 0; i < clients.length; i++) {
        var w = clients[i];
        var cands = [String(w.internalId)];
        try { cands.push(String(w.windowId)); } catch (e) {}
        if (cands.indexOf(want) >= 0) return w;
    }
    return null;
}
function __uiaHandle(args) {
    var op = args[0];
    try {
        if (op === "list") return __uiaList();
        if (op === "outputs") return __uiaOutputs();
        if (op === "active") { var a = workspace.activeWindow; return a ? JSON.stringify(__uiaOne(a)) : "null"; }
        var w = __uiaFind(args[1]);
        if (!w) return JSON.stringify({error: "no-such-window", id: String(args[1])});
        if (op === "info") return JSON.stringify(__uiaOne(w));
        if (op === "activate" || op === "focus") { workspace.activeWindow = w; return JSON.stringify(__uiaOne(w)); }
        if (op === "minimize") { w.minimized = true; return JSON.stringify(__uiaOne(w)); }
        if (op === "unminimize") { w.minimized = false; return JSON.stringify(__uiaOne(w)); }
        if (op === "maximize") { w.setMaximize(true, true); return JSON.stringify(__uiaOne(w)); }
        if (op === "restore") { w.setMaximize(false, false); w.minimized = false; return JSON.stringify(__uiaOne(w)); }
        if (op === "move") { w.frameGeometry = {x: args[2], y: args[3], width: w.frameGeometry.width, height: w.frameGeometry.height}; return JSON.stringify(__uiaOne(w)); }
        if (op === "resize") { w.frameGeometry = {x: w.frameGeometry.x, y: w.frameGeometry.y, width: args[2], height: args[3]}; return JSON.stringify(__uiaOne(w)); }
        if (op === "move-resize") { w.frameGeometry = {x: args[2], y: args[3], width: args[4], height: args[5]}; return JSON.stringify(__uiaOne(w)); }
        if (op === "close") { w.closeWindow(); return JSON.stringify({closed: String(args[1])}); }
        if (op === "capture") {
            var o = w.output;
            var img = (typeof readShadowBuffer === "function") ? readShadowBuffer(o) : null;
            if (!img || !img.size || img.size.width === 0) return JSON.stringify({error: "no-shadow-buffer"});
            var f = w.frameGeometry, g = o.geometry;
            var scale = img.size.width / g.width;
            var cx = Math.round((f.x - g.x) * scale), cy = Math.round((f.y - g.y) * scale);
            var cw = Math.round(f.width * scale), ch = Math.round(f.height * scale);
            if (cw <= 0 || ch <= 0) return JSON.stringify({error: "window-offscreen"});
            var saved = img.save(args[2], "PNG");
            if (!saved) return JSON.stringify({error: "save-failed", path: args[2]});
            return JSON.stringify({path: args[2], outputCrop: {x: cx, y: cy, width: cw, height: ch},
                                   scale: Number(scale)});
        }
        return JSON.stringify({error: "unknown-op", op: op});
    } catch (e) {
        return JSON.stringify({error: "script-error", message: String(e)});
    }
}
var __uiaLast = 0;
function __uiaResume() {
    var seq = Number(readConfig("kde_uia_seq", 0));
    var file = readConfig("kde_uia_args", "");
    var dir = readConfig("kde_uia_out", "");
    if (!file || !dir || seq <= __uiaLast) return;
    var args = null;
    try { args = JSON.parse(file); } catch (e) { args = ["list"]; }
    writeFile(dir + "/result-" + seq + ".json", JSON.stringify({seq: seq, result: __uiaHandle(args)}));
    __uiaLast = seq;
}
__uiaResume();
options.configChanged.connect(__uiaResume);
"""

_CONFIG_GROUP = "Script-" + _SCRIPT_NAME


def _run(argv: list[str], *, timeout: float = 5.0) -> tuple[int, str, str]:
    try:
        proc = subprocess.run(argv, capture_output=True, text=True, timeout=timeout, check=False)
    except subprocess.TimeoutExpired:
        raise KdeUiaError(f"{Path(argv[0]).name} did not answer within {timeout:g}s", code="TIMEOUT",
                          hint="The desktop service may be busy or restarting; retry once.") from None
    except OSError as exc:
        raise BackendUnavailableError(f"cannot run {argv[0]}: {exc}") from exc
    return proc.returncode, proc.stdout or "", proc.stderr or ""


def _pick_dbus_tool() -> tuple[str, str] | None:
    """Pick a D-Bus CLI.

    ``qdbus6``/``qdbus`` can also write the KWin script's KConfig section
    directly, so they are preferred. ``busctl``/``gdbus`` can call KWin but
    need ``kwriteconfig6`` to *write* config — that requirement is enforced by
    :class:`DbusCli` so a machine with ``busctl`` but no ``kwriteconfig6``
    degrades to the next backend instead of failing later.
    """
    for name in ("qdbus6", "qdbus", "busctl", "gdbus"):
        exe = shutil.which(name)
        if exe:
            return name, exe
    return None


def _kwriteconfig() -> str | None:
    return shutil.which("kwriteconfig6") or shutil.which("kwriteconfig5")


#: One place for the KWin-bridge dependency hint, Arch first (primary target).
_KCONFIG_HINT = (
    "The KWin scripting bridge needs a D-Bus tool plus KConfig's CLI. "
    "Arch: sudo pacman -S qt6-tools kconfig | "
    "Debian/Ubuntu: sudo apt install qdbus-qt6 kconfig-cli | "
    "Fedora: sudo dnf install qt6-qttools kf6-kconfig"
)


class DbusCli:
    """Minimal D-Bus invocation with qdbus6/qdbus/busctl/gdbus dialects."""

    def __init__(self) -> None:
        picked = _pick_dbus_tool()
        if picked is None:
            raise BackendUnavailableError(
                "no D-Bus command-line tool (qdbus6, qdbus, busctl, gdbus) is on PATH",
                hint=_KCONFIG_HINT,
            )
        self.kind, self.exe = picked
        # A tool that cannot write config cannot drive the KWin script bridge;
        # say so *here*, with the right package name for the distribution.
        if self.kind in ("busctl", "gdbus") and _kwriteconfig() is None:
            raise BackendUnavailableError(
                f"{self.kind} is the only D-Bus tool, but the KWin script bridge also needs kwriteconfig6 "
                "to hand it each command",
                hint=_KCONFIG_HINT,
                details={"dbusTool": self.kind},
            )

    def call(self, service: str, path: str, iface: str, method: str, args: list[Any], *, timeout: float = 8.0) -> str:
        if self.kind in ("qdbus6", "qdbus"):
            argv = [self.exe, "--literal", service, path, f"{iface}.{method}", *[str(a) for a in args]]
        elif self.kind == "busctl":
            types = "".join("s" if isinstance(a, str) else "i" for a in args)
            values = [str(a) for a in args]
            argv = [self.exe, "--user", "call", service, path, iface, method, types, *values]
        else:
            escaped = []
            for a in args:
                text = str(a).replace("\\", "\\\\").replace("'", "\\'")
                escaped.append(f"'{text}'")
            argv = [self.exe, "call", "--session", "--dest", service, "--object-path", path,
                    "--method", f"{iface}.{method}", *escaped]
        code, stdout, stderr = _run(argv, timeout=timeout)
        if code != 0:
            raise KdeUiaError(
                f"D-Bus call {iface}.{method} on {service} failed: {(stderr or stdout).strip()}",
                code="BACKEND_UNAVAILABLE",
                hint="KWin may not be running, or the session bus is not the desktop's.",
            )
        return stdout

    def read_config(self, key: str) -> str | None:
        """Read ``[Script-kde-uia-window-probe][General] <key>`` from KWin's config."""
        try:
            if self.kind in ("qdbus6", "qdbus"):
                out = self.call("org.kde.KWin", "/KWin", "org.kde.KConfig", "readEntry",
                                [_CONFIG_GROUP, "General", key])
                return out.strip() or None
            kwrite = _kwriteconfig()
            if kwrite is None:
                return None
            reader = shutil.which("kreadconfig6") or shutil.which("kreadconfig5")
            if reader is None:
                return None
            code, out, _ = _run([reader, "--file", "kwinrc", "--group", _CONFIG_GROUP, "--key", key], timeout=3.0)
            return out.strip() or None if code == 0 else None
        except KdeUiaError:
            return None

    def write_config(self, entries: list[tuple[str, str]]) -> None:
        if self.kind in ("qdbus6", "qdbus"):
            for key, value in entries:
                self.call("org.kde.KWin", "/KWin", "org.kde.KConfig", "writeEntry",
                          [_CONFIG_GROUP, "General", key, value], timeout=3.0)
            return
        kwrite = _kwriteconfig()
        if kwrite is None:
            raise BackendUnavailableError(
                f"{self.kind} cannot write KWin script config and no kwriteconfig5/6 exists",
                hint=_KCONFIG_HINT,
            )
        for key, value in entries:
            code, _, stderr = _run([kwrite, "--file", "kwinrc", "--group", _CONFIG_GROUP,
                                    "--key", key, value], timeout=3.0)
            if code != 0:
                raise KdeUiaError(f"kwriteconfig failed: {stderr.strip()}", code="BACKEND_UNAVAILABLE")


class KwinBackend:
    """KWin scripting backend shared by window management and screenshots."""

    def __init__(self, *, script_name: str = _SCRIPT_NAME) -> None:
        self.script_name = script_name
        self.bus = DbusCli()
        self.script_file = Path.home() / ".local" / "share" / "kwin" / "scripts" / f"{script_name}.js"
        self.state_dir = Path(tempfile.gettempdir()) / "kde-uia"
        self.state_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------- install
    def _load(self) -> int:
        out = self.bus.call("org.kde.KWin", "/Scripting", "org.kde.kwin.Scripting", "loadScript",
                            [str(self.script_file)])
        for token in out.replace("(", " ").replace(")", " ").split():
            digits = "".join(ch for ch in token if ch.isdigit())
            if digits:
                return int(digits)
        raise KdeUiaError(f"KWin loadScript returned no id: {out.strip()!r}", code="BACKEND_UNAVAILABLE")

    def ensure_loaded(self) -> None:
        """Write the script, load it once for this desktop session and run it."""
        marker = self.state_dir / "kwin-script.json"
        current = self.script_file.read_text(encoding="utf-8") if self.script_file.is_file() else None
        fresh = current != _SCRIPT_JS
        if fresh:
            self.script_file.parent.mkdir(parents=True, exist_ok=True)
            self.script_file.write_text(_SCRIPT_JS, encoding="utf-8")
        if marker.is_file() and not fresh:
            return
        script_id = self._load()
        marker.write_text(json.dumps({"id": script_id}), encoding="utf-8")
        self.bus.call("org.kde.KWin", "/Scripting", "org.kde.kwin.Scripting", "start", [str(script_id)])
        self.bus.write_config([("kde_uia_out", str(self.state_dir)), ("kde_uia_seq", "0"),
                               ("kde_uia_args", ""), ("kde_uia_busy", "0")])

    # ------------------------------------------------------------- command
    def command(self, op: str, window_id: str | None = None, params: list[Any] | None = None, *, timeout: float = 15.0) -> Any:
        self.ensure_loaded()
        seq_file = self.state_dir / "seq"
        try:
            seq = int(seq_file.read_text(encoding="utf-8").strip())
        except (OSError, ValueError):
            seq = 0
        seq += 1
        result_path = self.state_dir / f"result-{seq}.json"
        result_path.unlink(missing_ok=True)
        args: list[Any] = [op]
        if window_id is not None:
            args.append(str(window_id))
        args.extend(params or [])
        self.bus.write_config([("kde_uia_busy", "1"), ("kde_uia_args", json.dumps(args)),
                               ("kde_uia_seq", str(seq))])
        seq_file.write_text(str(seq), encoding="utf-8")
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if result_path.is_file():
                try:
                    payload = json.loads(result_path.read_text(encoding="utf-8"))
                except (OSError, json.JSONDecodeError):
                    time.sleep(0.02)
                    continue
                raw = payload.get("result")
                value = json.loads(raw) if isinstance(raw, str) and raw[:1] in "[{\"n" else raw
                if isinstance(value, dict) and value.get("error"):
                    self._raise(value)
                return value
            time.sleep(0.02)
        self.bus.write_config([("kde_uia_busy", "0")])
        raise KdeUiaError(
            f"the KWin script did not answer `{op}` within {timeout:g}s",
            code="TIMEOUT",
            hint="KWin may be restarting. Retry; if it persists, run `kde-uia doctor`.",
        )

    @staticmethod
    def _raise(result: dict[str, Any]) -> None:
        error = result.get("error")
        if error == "no-such-window":
            raise NotFoundError(f"no window with id {result.get('id')!r}", hint="Run `kde-uia windows`.")
        if error == "no-shadow-buffer":
            raise BackendUnavailableError(
                "the compositor exposes no shadow buffer for that window's output",
                hint="Try `kde-uia screenshot --strategy spectacle` (KDE) or enable compositing.",
            )
        if error == "window-offscreen":
            raise KdeUiaError("the window is outside its output's geometry", code="SCREENSHOT_FAILED")
        raise KdeUiaError(
            f"KWin script error {error!r}: {result.get('message', '')}".strip(),
            code="BACKEND_UNAVAILABLE",
        )

    # ----------------------------------------------------------------- API
    def windows(self) -> list[dict[str, Any]]:
        return self.command("list") or []

    def active(self) -> dict[str, Any] | None:
        return self.command("active") or None

    def outputs(self) -> list[dict[str, Any]]:
        return self.command("outputs") or []

    def info(self, window_id: str) -> dict[str, Any]:
        return self.command("info", window_id)

    def act(self, op: str, window_id: str, params: list[Any] | None = None) -> Any:
        if op not in ACTIONS:
            raise UsageError(f"unknown window action {op!r}", hint=f"Actions: {', '.join(ACTIONS)}.")
        return self.command(op, window_id, params)

    def capture(self, window_id: str, path: Path) -> dict[str, Any]:
        return self.command("capture", window_id, [str(path)])


class X11Backend:
    """EWMH window management through ``wmctrl`` / ``xdotool``."""

    def __init__(self) -> None:
        import os

        if not os.environ.get("DISPLAY"):
            raise BackendUnavailableError("the X11 backend needs DISPLAY (not a pure Wayland session)")
        self.wmctrl = shutil.which("wmctrl")
        self.xdotool = shutil.which("xdotool")
        if not self.wmctrl and not self.xdotool:
            raise BackendUnavailableError(
                "the X11 window backend needs wmctrl or xdotool",
                hint="Arch: sudo pacman -S wmctrl xdotool | Debian: sudo apt install wmctrl xdotool | Fedora: sudo dnf install wmctrl xdotool",
            )

    def _require(self, tool: str | None, name: str) -> str:
        if not tool:
            raise BackendUnavailableError(f"this X11 action needs {name}", hint=f"Install {name}.")
        return tool

    def windows(self) -> list[dict[str, Any]]:
        active = self._active_id()
        if self.wmctrl:
            _, out, _ = _run([self.wmctrl, "-l", "-p", "-G"])
            result = []
            for line in out.splitlines():
                parts = line.split(None, 7)
                if len(parts) < 8:
                    continue
                hexid, desktop, pid, x, y, w, h = parts[:7]
                result.append({
                    "id": hexid, "caption": parts[7], "resourceClass": self._class(hexid),
                    "pid": int(pid) if pid.isdigit() else 0,
                    "desktop": int(desktop) if desktop.lstrip("-").isdigit() else -1,
                    "frame": {"x": int(x), "y": int(y), "width": int(w), "height": int(h)},
                    "active": active is not None and hexid.lower().endswith(active.lower().lstrip("0x")[-8:]) if active else False,
                    "minimized": False,
                })
            return result
        xdotool = self._require(self.xdotool, "xdotool")
        _, out, _ = _run([xdotool, "search", "--onlyvisible", "--name", ""])
        result = []
        for hexid in out.split():
            _, name, _ = _run([xdotool, "getwindowname", hexid])
            _, geom, _ = _run([xdotool, "getwindowgeometry", "--shell", hexid])
            rect = _geometry_shell(geom)
            result.append({"id": hexid, "caption": name.strip(), "resourceClass": self._class(hexid),
                           "frame": rect, "active": active == hexid, "minimized": False, "pid": 0, "desktop": -1})
        return result

    def _active_id(self) -> str | None:
        if not self.xdotool:
            return None
        code, out, _ = _run([self.xdotool, "getactivewindow"])
        return out.strip() if code == 0 and out.strip() else None

    @staticmethod
    def _class(hexid: str) -> str:
        xprop = shutil.which("xprop")
        if not xprop:
            return ""
        code, out, _ = _run([xprop, "-id", hexid, "WM_CLASS"])
        if code != 0 or "=" not in out:
            return ""
        values = [v.strip().strip('"') for v in out.split("=", 1)[1].split(",")]
        return values[-1] if values else ""

    def active(self) -> dict[str, Any] | None:
        active = self._active_id()
        if not active:
            return None
        for info in self.windows():
            if info.get("id") == active:
                return info
        return {"id": active, "caption": "", "resourceClass": "", "frame": None, "active": True}

    def info(self, window_id: str) -> dict[str, Any]:
        for info in self.windows():
            if info["id"] == window_id:
                return info
        raise NotFoundError(f"no X11 window with id {window_id!r}")

    def act(self, op: str, window_id: str, params: list[Any] | None = None) -> Any:
        params = params or []
        xdotool = self.xdotool
        if op == "close":
            if self.wmctrl:
                _run([self.wmctrl, "-i", "-c", window_id])
                return {"closed": window_id}
            _run([self._require(xdotool, "xdotool"), "windowkill", window_id])
            return {"closed": window_id}
        xdotool = self._require(xdotool, "xdotool")
        table = {
            "activate": ["windowactivate", "--sync", window_id],
            "focus": ["windowfocus", "--sync", window_id],
            "minimize": ["windowminimize", window_id],
            "unminimize": ["windowmap", window_id],
            "maximize": ["windowsize", window_id, "100%", "100%"],
            "restore": ["windowmap", window_id],
            "move": ["windowmove", window_id, str(params[0]), str(params[1])],
            "resize": ["windowsize", window_id, str(params[0]), str(params[1])],
            "move-resize": ["windowmove", window_id, str(params[0]), str(params[1])],
        }
        if op not in table:
            raise UsageError(f"the X11 backend cannot perform {op!r}")
        _run([xdotool, *table[op]])
        if op == "move-resize":
            _run([xdotool, "windowsize", window_id, str(params[2]), str(params[3])])
        return self.info(window_id)


def _geometry_shell(text: str) -> dict[str, int] | None:
    values: dict[str, int] = {}
    for line in text.splitlines():
        if "=" in line:
            key, _, value = line.partition("=")
            if value.strip().lstrip("-").isdigit():
                values[key.strip()] = int(value)
    if all(k in values for k in ("X", "Y", "WIDTH", "HEIGHT")):
        return {"x": values["X"], "y": values["Y"], "width": values["WIDTH"], "height": values["HEIGHT"]}
    return None


def backend_name(actor: Any) -> str:
    if isinstance(actor, KwinBackend):
        return "kwin"
    if isinstance(actor, X11Backend):
        return "x11"
    return "unknown"


def select_backend(mode: str = "auto") -> Any:
    """Return a working KWin or X11 backend; ``auto`` prefers KWin."""
    if mode not in ("auto", "kwin", "x11"):
        raise UsageError(f"unknown window backend {mode!r}", hint="auto | kwin | x11")
    errors: list[str] = []
    if mode in ("auto", "kwin"):
        try:
            kwin = KwinBackend()
            kwin.ensure_loaded()
            return kwin
        except KdeUiaError as exc:
            errors.append(f"kwin: {exc.message}")
    if mode in ("auto", "x11"):
        try:
            return X11Backend()
        except KdeUiaError as exc:
            errors.append(f"x11: {exc.message}")
    raise BackendUnavailableError(
        "no window-management backend is available: " + "; ".join(errors),
        hint="Arch: sudo pacman -S qt6-tools kconfig xdotool wmctrl | Debian: sudo apt install qdbus-qt6 kconfig-cli xdotool wmctrl",
    )


@dataclass
class WindowCatalog:
    """Uniform view over whichever backend answered."""

    backend: Any
    name: str = field(default="")

    def __post_init__(self) -> None:
        self.name = backend_name(self.backend)

    def list(self) -> list[dict[str, Any]]:
        return self.backend.windows()

    def active(self) -> dict[str, Any] | None:
        return self.backend.active()

    def find(self, *, window_id: str | None = None, title: str | None = None) -> dict[str, Any]:
        windows = self.list()
        if window_id:
            for info in windows:
                if str(info.get("id")) == window_id:
                    return info
            return self.backend.info(window_id)
        if title is not None:
            need = title.casefold()
            matches = [w for w in windows if need in (w.get("caption") or "").casefold()]
            if not matches:
                listing = ", ".join(repr(w.get("caption")) for w in windows[:10])
                raise NotFoundError(f"no window title contains {title!r}", hint=f"Open windows: {listing}.")
            if len(matches) > 1:
                listing = ", ".join(f"{w.get('caption')!r} ({w.get('id')})" for w in matches[:10])
                raise UsageError(f"{len(matches)} windows match {title!r}: {listing}", hint="Pass an exact window id instead.")
            return matches[0]
        raise UsageError("window selection needs a window id or a title")

    def act(self, action: str, window_id: str, params: list[Any] | None = None) -> Any:
        return self.backend.act(action, window_id, params)
